describe('the approximated kernels', () => {
    it.each(Object.keys(UNARY_VECTORS))('reproduces every golden bit pattern: %s', (name) => {
        const f = UNARY[name]!;
        const rows = UNARY_VECTORS[name]!;
        // Compared as whole arrays so one failure names every input that moved, not just the first.
        expect(rows.map(([x]) => bits(f(x)))).toStrictEqual(rows.map(([, want]) => want));
    });

    it.each(Object.keys(BINARY_VECTORS))('reproduces every golden bit pattern: %s', (name) => {
        const f = BINARY[name]!;
        const rows = BINARY_VECTORS[name]!;
        expect(rows.map(([a, b]) => bits(f(a, b)))).toStrictEqual(rows.map(([, , want]) => want));
    });

    it('covers every function the module approximates', () => {
        expect(new Set(Object.keys(UNARY_VECTORS))).toStrictEqual(new Set(Object.keys(UNARY)));
        expect(new Set(Object.keys(BINARY_VECTORS))).toStrictEqual(new Set(Object.keys(BINARY)));
    });
});

describe('the seeded stream', () => {
    it.each(STREAM_VECTORS)('reproduces the first draws bit for bit: seed %i', (seed, draws) => {
        const r = new SeededRandom(seed);
        const actual: string[] = [];
        for (let i = 0; i < draws.length; i++) actual.push(bits(r.next()));
        expect(actual).toStrictEqual(draws);
    });

    it.each(STREAM_VECTORS)('reaches the same four state words: seed %i', (seed, draws, state) => {
        // The state, not just the draws: a rewind restores these words, so a peer that resumed
        // from a divergent state would draw correctly for exactly zero ticks.
        const r = new SeededRandom(seed);
        for (let i = 0; i < draws.length; i++) r.next();
        expect(r.capture()).toStrictEqual(state);
    });
});
